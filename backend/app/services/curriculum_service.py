class CurriculumService:
    @staticmethod
    def list_curriculum_days() -> List[Dict[str, Any]]:
        return [
            {
                "day": k,
                "title": v["title"],
                "age_group": v["age_group"],
                "topic": v["topic"],
                "programme": v["programme"],
                "materials": v["materials"],
                "scene_count": len(v["scenes"])
            }
            for k, v in CURRICULUM_DATA.items()
        ]

    @staticmethod
    def get_day(day_key: str) -> Optional[Dict[str, Any]]:
        key = day_key.strip().upper()
        return CURRICULUM_DATA.get(key)

